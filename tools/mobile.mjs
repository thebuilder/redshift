// Mobile smoke test: phone-sized landscape viewport with real touch input (CDP).
import { chromium } from 'playwright-core';
const [,, url, outDir = '/tmp/claude-0', w = '844', h = '390'] = process.argv;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: +w, height: +h }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(url);
await page.waitForTimeout(4000);
const shot = async (n) => page.screenshot({ path: `${outDir}/m_${n}.png`, timeout: 180000 });
const tick = (n) => page.evaluate((n) => { const g = window.__redshift; for (let i = 0; i < n; i++) g.tick(1 / 30); return [g.state, g.sim.phase, +(g.sim.speed * 3.6).toFixed(0), document.body.classList.contains('touch'), document.getElementById('touch')?.className]; }, n);
await page.evaluate(() => { document.getElementById('boot').style.display = 'none'; });
await tick(2);
await shot('menu');
await page.tap('.lv');
console.log('after tap card', await tick(10));
await shot('intro');
await page.tap('#intro');
console.log('after tap intro', await tick(2));
const cdp = await ctx.newCDPSession(page);
const center = async (sel) => page.evaluate((sel) => { const r = document.querySelector(sel).getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; }, sel);
for (let i = 0; i < 5; i++) console.log('countdown', await tick(20));
await shot('countdown');
const thr = await center('#touch .t-thr');
const stick = { x: 150, y: +h - 120 };
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: thr.x, y: thr.y, id: 1 }, { x: stick.x, y: stick.y, id: 2 }] });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: thr.x, y: thr.y, id: 1 }, { x: stick.x + 30, y: stick.y, id: 2 }] });
console.log('held throttle', await tick(12), await page.evaluate(() => JSON.stringify(window.__redshift.input.touch)));
await shot('ground');
for (let i = 0; i < 12; i++) { const r = await tick(10); if (r[1] === 'air') break; }
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
console.log('air?', await tick(4));
const lift = await center('#touch .t-lift');
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: lift.x, y: lift.y, id: 3 }] });
console.log('lift', await tick(8), await page.evaluate(() => JSON.stringify(window.__redshift.input.touch)));
await shot('air');
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
console.log(logs.slice(-15).join('\n'));
await browser.close();
